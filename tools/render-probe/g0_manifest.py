"""Write the G0 attribution corpus manifests.

    python g0_manifest.py <probe.exe> <out dir>

The measured corpus is a set of private local documents plus the synthetic
fixtures under `corpus/`. The private documents are never copied, and their
paths and names are never committed:

- `g0-corpus.local.json` (beside this script, git-ignored) lists them:
  `[{"id": ..., "role": ..., "path": ..., "pages_selected": ..., "exercises": ...}]`.
  Ids must be neutral (`map-b`, `shading-a`), not derived from a file name.
- `<out dir>/manifest.json` is the published manifest: id, role, page
  selection, size and SHA-256, without any path for a private document.
- `<out dir>/manifest.local.json` (git-ignored) is the same with paths; the
  matrix and flamegraph scripts read it.

The probe is used only to read page counts (`probe census --max-pages 1`).
"""

from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
PRIVATE = "private local document; pinned by hash, not redistributed; licence not assessed"


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def page_count(probe, path):
    try:
        out = subprocess.run([probe, "census", path, "--max-pages", "1"], capture_output=True,
                             text=True, timeout=120).stdout
        for line in out.splitlines():
            row = json.loads(line)
            if "pages" in row:
                return row["pages"]
    except Exception:  # noqa: BLE001 - best effort
        pass
    return None


def main():
    probe, out_dir = os.path.abspath(sys.argv[1]), sys.argv[2]
    local_list = os.path.join(HERE, "g0-corpus.local.json")
    documents = json.load(open(local_list, encoding="utf-8")) if os.path.exists(local_list) else []
    if not documents:
        print("no g0-corpus.local.json: only the synthetic fixtures are listed", file=sys.stderr)
    entries = []
    for doc in documents:
        path = doc["path"]
        if not os.path.exists(path):
            print("missing:", doc["id"], file=sys.stderr)
            continue
        entries.append({
            "id": doc["id"], "role": doc["role"], "path": path,
            "pages_selected": doc["pages_selected"], "pages": page_count(probe, path),
            "bytes": os.path.getsize(path), "sha256": sha256(path),
            "exercises": doc.get("exercises", ""), "redistributable": False,
            "provenance": PRIVATE,
        })
    for sub, role in (("vector", "synthetic-vector"), ("text", "synthetic-text")):
        folder = os.path.join(REPO, "corpus", sub)
        for name in sorted(os.listdir(folder)):
            if not name.endswith(".pdf"):
                continue
            path = os.path.join(folder, name)
            entries.append({
                "id": "syn-" + name[:-4], "role": role,
                "path": "corpus/" + sub + "/" + name, "pages_selected": "0",
                "pages": page_count(probe, path), "bytes": os.path.getsize(path),
                "sha256": sha256(path), "exercises": "see corpus/" + sub + "/NOTES.md",
                "redistributable": True,
                "provenance": "synthetic; generated by `probe synth`; MIT (repository licence)",
            })
    public = [e if e["redistributable"] else {k: v for k, v in e.items() if k != "path"} for e in entries]
    for name, data in (("manifest.local.json", entries), ("manifest.json", public)):
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as handle:
            json.dump(data, handle, indent=1, ensure_ascii=False)
            handle.write("\n")
    print(len(entries), "entries ->", out_dir)


if __name__ == "__main__":
    main()
